-- `series_game_no` 가 '실제 몇 번째 세트였나' 가 **아니라는** 사실을 스키마에 박는다.
--
-- 왜 이 마이그레이션이 있나:
--   대회 기록의 출처(나무위키 결과표)는 **시리즈 스코어만** 준다 — '2:1'.
--   세트별로 누가 이겼는지는 없다. 그래서 적재할 때 승자 세트를 앞에 몰아 넣는다.
--   지금 DB 의 모든 2:1 경기는 예외 없이 승·승·패 순으로 들어가 있다.
--
--   합계는 맞다. 순서는 우리가 만든 것이다.
--
--   이걸 모르고 화면에 '1세트 승 / 2세트 승 / 3세트 패' 를 그렸다가 지웠다.
--   `2:1` 이 이미 같은 정보를 담고 있어 길이만 세 배가 되는 데다,
--   무엇보다 **모르는 걸 아는 척**하는 표시였다.
--
--   컬럼은 그대로 둔다. 한 시리즈 안에서 세트를 구분하는 키로는 여전히 필요하고,
--   (series_id, series_game_no) 유니크 인덱스가 판수 부풀림을 막고 있다.
--
--   나중에 세트별 승패를 실제로 긁어오면(나무위키 본문에 WIN/LOSE 가 있는 회차가 있다)
--   그때 이 주석을 고치고 화면에도 되살리면 된다.

COMMENT ON COLUMN match.series_game_no IS
  '한 다전제 안에서 세트를 구분하는 일련번호(1부터). '
  '⚠ 실제 경기 순서가 아니다 — 출처가 시리즈 스코어만 주므로 승자 세트를 앞에 몰아 넣는다. '
  '세트별 승패를 확보하기 전까지 이 번호로 "몇 세트에 졌나" 를 말할 수 없다.';
