-- 수기 내전 경기의 승패가 **무엇을 보고** 정해졌는지 남긴다.
--
-- 왜: 채팅 `!공지` 만 믿었다가 실제로 틀렸다. 2026-08-08 이상호배 시그니처CK
-- 2부 3세트에서 공지가 이렇게 왔다:
--     4:45:37 [하늘하늘_] 상호팀 2 : 1 성훈팀
--     4:46:04 [상구미]    상호팀 1 : 2 성훈팀
-- 직전 점수가 1:1 이라 둘 다 '한 칸 전진' 이라서 점수만으로는 못 고른다.
-- 먼저 온 쪽을 채택했더니 그게 오기였고, 승자가 뒤집힌 채 사이트에 올라갔다.
--
-- 그래서 승패의 **정본은 채팅이 아니라 LoL 최종 결과 화면**이다. 거기엔 승리/패배·
-- 10명 챔피언·KDA·게임 길이가 통째로 있고 사람이 잘못 칠 여지가 없다.
-- 그 화면을 어디서 봤는지를 이 칼럼에 적는다 — 나중에 누가 물어도 되짚을 수 있어야 한다.
--
-- ★ NOT NULL 로 걸지 않는다. 멸망전처럼 **주최측 발표**가 원천인 대회는 방송
--   결과 화면이 없고, 그것도 정당한 근거다. 방송에서 읽어 넣는 내전(kind='scrim')만
--   필수이고, 그 강제는 seed-tournament 가 파일 단위로 한다 — 어느 경기가 근거를
--   빠뜨렸는지 이름으로 말해 줄 수 있어야 하기 때문이다.

ALTER TABLE match ADD COLUMN result_evidence text;

COMMENT ON COLUMN match.result_evidence IS
  '이 경기의 승패를 확정한 결과 화면 지점 (VOD 시각 · 프레임 파일명). '
  '방송을 읽어 넣은 내전은 필수 — 채팅 공지는 단서일 뿐 정본이 아니다.';
