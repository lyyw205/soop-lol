-- FC 계정별 목록 커서 — 「이 계정의 목록을 어디까지 읽었나」.
--
-- ★ 왜 필요한가 (2026-09-26)
--   넥슨 경기 목록은 한국 날짜 기준 최근 30일만 준다(실측, docs/FCO-TIME-SAMPLES.md).
--   한 페이지(100건)만 받던 수집은 새 계정의 옛 경기를 못 받았고, 그 사이 30일이 지나
--   뿌챔스 4경기가 영구히 사라졌다. 그래서 목록을 넘겨 받되, 매일 수집이 끝까지 가지
--   않도록 멈출 자리가 필요하다.
--
-- ★ 「이미 저장된 경기」를 멈출 자리로 쓰지 않는 이유
--   경기는 상대 스트리머의 목록으로도 들어온다. 새 계정은 첫 페이지부터 등록된 스트리머와의
--   경기(=이미 저장됨)를 만나 거기서 멈춰 버린다 — 그물을 넓혀 가는 수집이 그대로 끊긴다.
--   그래서 멈출 자리는 경기 저장 여부가 아니라 **이 계정의 목록을 끝까지 읽은 시점**이다.
--
-- list_synced_until = 마지막으로 목록을 빈틈없이 읽었을 때 본 가장 새 경기의 시작 시각
--   (넥슨 matchId 앞 8자리 = 시작 유닉스 초). NULL = 아직 한 번도 끝까지 못 읽었다 → 끝까지 간다.

-- IF NOT EXISTS: 0040(남의 번호)이 보류 중이라 이 문장만 먼저 손으로 적용했다(2026-09-26). 러너가 나중에 돌려도 무해하다.
ALTER TABLE fco_account ADD COLUMN IF NOT EXISTS list_synced_until timestamptz;

COMMENT ON COLUMN fco_account.list_synced_until IS
  '이 계정 목록을 빈틈없이 읽은 지점(가장 새 경기의 시작 시각). 다음 수집은 이보다 오래된 경기에서 멈춘다(여유 2시간). NULL 이면 끝까지 읽는다.';
