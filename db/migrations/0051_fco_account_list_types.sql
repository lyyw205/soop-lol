-- FC 목록 커서(0041 list_synced_until)가 **어느 경기 모드를 읽은 뒤의 커서인지** 같이 적는다.
--
-- 문제: 커서는 계정당 하나인데 경기 모드(matchtype)는 여럿이다. 40(친선)만 읽던 계정에 50(공식)을 추가하면,
--   새 모드가 40 의 커서를 물려받아 「커서 −2시간」에서 목록 넘기기를 멈춘다 — 그 모드의 최근 30일 과거 경기를
--   영구히 못 받는다(넥슨은 30일이 지난 경기를 지운다). 수동 `fco:sync --matchtypes=50` 도 같은 커서를 옮겨
--   40 의 못 읽은 구간을 건너뛴다.
-- 규칙(sync.ts): 커서에서 멈추는 것은 **이 배열에 든 모드뿐**이다. 든 적 없는 모드는 끝까지 읽는다.
--   커서는 읽은 모드가 배열을 **모두 포함할 때만** 옮기고, 그때 배열에 읽은 모드를 더한다.
-- NULL(이 마이그레이션 이전의 계정)은 「어느 모드를 읽었는지 모른다」다 — 추측으로 채우지 않는다.
--   다음 수집이 한 번 끝까지(30일) 읽고 배열을 채운다. 목록 조회만 늘고 상세는 새 경기만 받는다.
ALTER TABLE fco_account ADD COLUMN IF NOT EXISTS list_synced_types integer[];

COMMENT ON COLUMN fco_account.list_synced_types IS
  'list_synced_until 이 가리키는 지점까지 빈틈없이 읽은 경기 모드(matchtype). 이 배열에 든 모드만 커서에서 멈추고, '
  '든 적 없는 모드는 끝까지 읽는다. NULL 이면 모른다 — 다음 수집이 끝까지 읽고 채운다.';
